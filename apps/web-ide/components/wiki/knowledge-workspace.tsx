function SimpleDiff({ a, b, tc }: { a: string; b: string; tc: ThemeColors }) {
  const aLines = a.split("\n");
  const bLines = b.split("\n");
  const aSet = new Set(aLines);
  const bSet = new Set(bLines);
  const rows: Array<{ kind: "add" | "del" | "ctx"; text: string }> = [];
  // Linee rimosse (in a, non in b)
  for (const line of aLines) {
    if (!bSet.has(line)) rows.push({ kind: "del", text: line });
  }
  // Linee aggiunte (in b, non in a)
  for (const line of bLines) {
    if (!aSet.has(line)) rows.push({ kind: "add", text: line });
  }
  return (
    <pre
      style={{
        background: tc.bgInput,
        padding: 10,
        borderRadius: 4,
        border: `1px solid ${tc.border}`,
        fontSize: 11.5,
        fontFamily: "monospace",
        overflow: "auto",
        maxHeight: 600,
        whiteSpace: "pre-wrap",
      }}
    >
      {rows.length === 0 ? (
        <span style={{ color: tc.textSecondary }}>(nessuna differenza)</span>
      ) : (
        rows.map((r, i) => (
          <div
            key={i}
            style={{
              color:
                r.kind === "add"
                  ? "#16a34a"
                  : r.kind === "del"
                    ? "#dc2626"
                    : tc.text,
            }}
          >
            {r.kind === "add" ? "+ " : r.kind === "del" ? "- " : "  "}
            {r.text || " "}
          </div>
        ))
      )}
    </pre>
  );
}
